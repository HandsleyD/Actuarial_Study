#!/usr/bin/env node
// Builds docs/exam-stats.js (pass marks and pass rates for every subject and
// sitting) from the examiners' reports under
// maths-study/resources/past-papers/processed/<CODE>/<YEAR>/<Month>/.
//
// Every report ends its commentary with a "C. Pass Mark" section along the
// lines of:
//
//   The Pass Mark for this exam was 60.
//   1089 presented themselves and 817 passed.
//
// The wording drifts between years ("was set at 58", "reduced the pass mark
// to 55", "Pass Mark: 60", sometimes a paragraph of explanation first), so
// the pass mark is taken as the LAST "pass mark ... was/at/as/to NN" in the
// text leading up to the "presented themselves" line.
//
// Subjects with two papers (CM1A/B, CS2A/B...) or two reports (CP1-1/-2)
// have one report per paper, each quoting the same combined figures. When
// they disagree (a typo in one of them) the first report's figures are kept
// and the difference is recorded as a note shown on the site.
//
// From September 2025 the reports are only published on the IFoA's
// members-only VLE, so those sittings are kept as short excerpts holding just
// the pass mark section rather than the full converted report.
//
// Re-run after adding new examiners' reports:
//   node scripts/extract-exam-stats.mjs
// or check that docs/exam-stats.js is up to date without writing it:
//   node scripts/extract-exam-stats.mjs --check

import { readFile, writeFile, readdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "maths-study/resources/past-papers/processed");
const OUT = join(ROOT, "docs/exam-stats.js");
const MONTHS = { April: "04", September: "09" };

const num = (s) => Number(s.replace(/,/g, ""));

function parseReport(text) {
  const flat = text.replace(/\s+/g, " ");
  const counts = flat.match(/([\d,]+) (?:candidates )?presented themselves,? and ([\d,]+) ?(?:candidates )?passed/i);
  if (!counts) return null;
  const before = flat.slice(Math.max(0, counts.index - 1500), counts.index);
  const marks = [...before.matchAll(/pass mark\b[^.]*?\b(?:was|is|at|as|to|of)\s+(\d{2})\b|pass mark:\s*(\d{2})\b/gi)];
  const last = marks[marks.length - 1];
  return {
    mark: last ? Number(last[1] || last[2]) : null,
    sat: num(counts[1]),
    passed: num(counts[2]),
  };
}

async function dirs(path) {
  try {
    return (await readdir(path, { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name);
  } catch {
    return [];
  }
}

async function build() {
  const stats = {};
  const problems = [];
  for (const code of (await dirs(SRC)).sort()) {
    const rows = [];
    for (const year of (await dirs(join(SRC, code))).sort()) {
      for (const month of (await dirs(join(SRC, code, year))).sort((a, b) => (MONTHS[a] || a).localeCompare(MONTHS[b] || b))) {
        if (!MONTHS[month]) continue;
        const dir = join(SRC, code, year, month);
        const files = (await readdir(dir)).filter((f) => f.includes("examiner-report") && f.endsWith(".md")).sort();
        let row = null;
        const notes = [];
        for (const f of files) {
          const r = parseReport(await readFile(join(dir, f), "utf8"));
          if (!r) {
            problems.push(`${code} ${month} ${year}: no pass figures found in ${f}`);
            continue;
          }
          if (!row) {
            row = { sitting: `${year}-${MONTHS[month]}`, ...r };
            continue;
          }
          for (const k of ["mark", "sat", "passed"]) {
            if (r[k] !== null && row[k] !== r[k]) {
              const label = { mark: "pass mark", sat: "candidates", passed: "passes" }[k];
              notes.push(`The reports for this sitting disagree on the number of ${label} (${row[k]} vs ${r[k]}); the first is shown.`);
            }
            if (row[k] === null) row[k] = r[k];
          }
        }
        if (!row) continue;
        if (row.mark === null) problems.push(`${code} ${month} ${year}: pass mark not found`);
        if (notes.length) row.note = notes.join(" ");
        rows.push(row);
      }
    }
    if (rows.length) stats[code] = rows;
  }
  return { stats, problems };
}

function render(stats) {
  const lines = Object.entries(stats).map(([code, rows]) => {
    const body = rows.map((r) => `    ${JSON.stringify(r)},`).join("\n");
    return `  ${code}: [\n${body}\n  ],`;
  });
  return `// GENERATED by scripts/extract-exam-stats.mjs from the examiners' reports in
// maths-study/resources/past-papers/processed/ -- don't edit by hand; re-run
// the script instead. sitting is "YYYY-MM"; mark is the pass mark (out of
// 100); sat/passed are the candidate counts the report gives.
const PASS_STATS = {
${lines.join("\n")}
};
`;
}

const { stats, problems } = await build();
problems.forEach((p) => console.error(`warning: ${p}`));
const out = render(stats);

if (process.argv.includes("--check")) {
  const current = await readFile(OUT, "utf8").catch(() => "");
  if (current.replace(/\r\n/g, "\n") !== out) {
    console.error("docs/exam-stats.js is out of date: run node scripts/extract-exam-stats.mjs");
    process.exit(1);
  }
  console.log("docs/exam-stats.js is up to date.");
} else {
  await writeFile(OUT, out);
  const n = Object.values(stats).reduce((a, r) => a + r.length, 0);
  console.log(`Wrote ${n} sittings across ${Object.keys(stats).length} subjects to docs/exam-stats.js.`);
}
